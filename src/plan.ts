/**
 * The LLM never writes raw code. It returns a JSON test plan that we validate
 * and then render to Playwright with a fixed template. That keeps generated
 * tests readable, reviewable and free of hallucinated APIs.
 */
export type Target =
  | { by: 'role'; role: string; value: string }
  | { by: 'label'; value: string }
  | { by: 'testid'; value: string }
  | { by: 'text'; value: string }
  | { by: 'placeholder'; value: string };

export type Step =
  | { action: 'goto'; value: string }
  | { action: 'fill'; target: Target; value: string }
  | { action: 'click'; target: Target }
  | { action: 'check'; target: Target }
  | { action: 'select'; target: Target; value: string }
  | { action: 'expectText'; value: string }
  | { action: 'expectVisible'; target: Target }
  | { action: 'expectUrl'; value: string };

export interface TestPlan {
  steps: Step[];
}

const ACTIONS = new Set(['goto', 'fill', 'click', 'check', 'select', 'expectText', 'expectVisible', 'expectUrl']);
const TARGET_KINDS = new Set(['role', 'label', 'testid', 'text', 'placeholder']);
const NEEDS_TARGET = new Set(['fill', 'click', 'check', 'select', 'expectVisible']);
const NEEDS_VALUE = new Set(['goto', 'fill', 'select', 'expectText', 'expectUrl']);

/** Reject malformed plans before they become code. Returns a list of problems (empty = valid). */
export function validatePlan(plan: unknown): string[] {
  const errors: string[] = [];
  const steps = (plan as TestPlan)?.steps;
  if (!Array.isArray(steps) || steps.length === 0) return ['plan has no steps'];
  steps.forEach((s: any, i) => {
    if (!ACTIONS.has(s?.action)) errors.push(`step ${i + 1}: unknown action "${s?.action}"`);
    if (NEEDS_TARGET.has(s?.action)) {
      if (!s.target || !TARGET_KINDS.has(s.target.by)) errors.push(`step ${i + 1}: missing or invalid target`);
      else if (s.target.by === 'role' && !s.target.role) errors.push(`step ${i + 1}: role target needs "role"`);
    }
    if (NEEDS_VALUE.has(s?.action) && typeof s.value !== 'string') errors.push(`step ${i + 1}: missing value`);
  });
  return errors;
}

const q = (s: string) => JSON.stringify(s);

export function renderLocator(t: Target): string {
  switch (t.by) {
    case 'role':
      return `page.getByRole(${q(t.role)}, { name: ${q(t.value)} })`;
    case 'label':
      return `page.getByLabel(${q(t.value)})`;
    case 'testid':
      return `page.getByTestId(${q(t.value)})`;
    case 'placeholder':
      return `page.getByPlaceholder(${q(t.value)})`;
    case 'text':
      return `page.getByText(${q(t.value)})`;
  }
}

function renderStep(s: Step): string {
  switch (s.action) {
    case 'goto':
      return `await page.goto(${q(s.value)});`;
    case 'fill':
      return `await ${renderLocator(s.target)}.fill(${q(s.value)});`;
    case 'click':
      return `await ${renderLocator(s.target)}.click();`;
    case 'check':
      return `await ${renderLocator(s.target)}.check();`;
    case 'select':
      return `await ${renderLocator(s.target)}.selectOption(${q(s.value)});`;
    case 'expectText':
      return `await expect(page.getByText(${q(s.value)})).toBeVisible();`;
    case 'expectVisible':
      return `await expect(${renderLocator(s.target)}).toBeVisible();`;
    case 'expectUrl':
      return `await expect(page).toHaveURL(new RegExp(${q(s.value)}));`;
  }
}

export function renderSpec(title: string, plan: TestPlan, scenario: string): string {
  const comment = scenario
    .trim()
    .split('\n')
    .map((l) => ` * ${l.trim()}`)
    .join('\n');
  const body = plan.steps.map((s) => `  ${renderStep(s)}`).join('\n');
  return `// Generated by playwright-ai-test-generator. Review before committing.
import { test, expect } from '@playwright/test';

/**
 * Scenario:
${comment}
 */
test(${q(title)}, async ({ page }) => {
${body}
});
`;
}
